// Precompute the dot-matrix Earth: Fibonacci-sphere points that fall on land.
// Writes src/data/land.js (window.SENTINEL_LAND = [lat*10, lon*10, ...]).
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const { feature } = require('topojson-client');
const land = feature(topo, topo.objects.land);
const polys = [];
for (const f of land.features) {
  const g = f.geometry;
  const list = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  for (const p of list) polys.push(p);
}
function inRing(x, y, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
const isLand = (lon, lat) => polys.some((p) => inRing(lon, lat, p[0]) && !p.slice(1).some((h) => inRing(lon, lat, h)));
const N = +(process.argv[2] || 36000), out = [];
const ga = Math.PI * (3 - Math.sqrt(5));
for (let i = 0; i < N; i++) {
  const y = 1 - (2 * (i + 0.5)) / N, r = Math.sqrt(1 - y * y), th = ga * i;
  const lat = (Math.asin(y) * 180) / Math.PI;
  let lon = ((((th * 180) / Math.PI) % 360) + 540) % 360 - 180;
  if (lat < -60) continue; // leave Antarctica out: it reads as noise at the bottom of the globe
  if (isLand(lon, lat)) out.push(Math.round(lat * 10), Math.round(lon * 10));
}
writeFileSync(new URL('../src/data/land.js', import.meta.url),
  `/* Land dots for the globe (lat*10, lon*10). Generated by render/make-globe.mjs from Natural Earth (public domain) via world-atlas. */\nwindow.SENTINEL_LAND = [${out.join(',')}];\n`);
console.log('dots:', out.length / 2);
